/**
 * Demo device and its virtual transport (plan §8.7).
 *
 * The device supports four data formats:
 *
 * - `sensor-a5` (default): the built-in A5 5A sensor protocol; it also accepts
 *   the 0x10 interval command;
 * - `firewater`, `justfloat`, `kv-text`: the three dashboard formats.
 *
 * Samples use virtual time `τ = n × interval / 1000`; a 10ms timer sends every
 * sample that the wall clock says is due (catching up in blocks, at most 1000
 * samples per tick). Framing is reimplemented here on purpose: `domains/link`
 * may only use `protocol/public.ts` and must not depend on its internals.
 */

import type { ByteTransport, TransportCapabilities, TransportSignals } from '../../transport/types'

/** Device memory key shared by all demo ports (plan §6.6). */
export const VIRTUAL_DEVICE_KEY = 'virtual'

/** Demo port capabilities: no line settings, DTR/RTS only, no break. */
export const VIRTUAL_CAPABILITIES: TransportCapabilities = {
  lineSettings: false,
  signals: true,
  break: false,
}

/** Data formats generated by the demo device (plan §6.6 / §8.7). */
export type DemoFormat = 'sensor-a5' | 'firewater' | 'justfloat' | 'kv-text'

/** Formats in settings-menu order. */
export const DEMO_FORMATS: readonly DemoFormat[] = [
  'sensor-a5',
  'firewater',
  'justfloat',
  'kv-text',
]

/** Default format from plan §6.6. */
export const DEMO_FORMAT_DEFAULT: DemoFormat = 'sensor-a5'

/** Interval bounds from plan §6.6. */
export const DEMO_INTERVAL_MIN = 1
export const DEMO_INTERVAL_MAX = 10_000
/** `sensor-a5` needs at least 100ms between reports (plan §6.6 / §8.6). */
export const DEMO_SENSOR_INTERVAL_MIN = 100
/** Default interval of `sensor-a5`. */
export const DEMO_INTERVAL_DEFAULT = 1000
/** Default interval when the UI switches to another format (plan §6.6). */
export const DEMO_INTERVAL_DEFAULT_OTHER = 10

/** Channel bounds; only `firewater` / `justfloat` use them (plan §6.6). */
export const DEMO_CHANNELS_MIN = 1
export const DEMO_CHANNELS_MAX = 16
export const DEMO_CHANNELS_DEFAULT = 8
/** `kv-text` always reports the 8 base channels (plan §6.6). */
export const DEMO_TEXT_CHANNELS = 8

/** Amplitude bounds of the `amp=` text command (plan §8.7). */
export const DEMO_AMP_MIN = 0
export const DEMO_AMP_MAX = 10
export const DEMO_AMP_DEFAULT = 1

/** Timer period and catch-up limit (plan §8.7). */
export const DEMO_TICK_MS = 10
export const DEMO_MAX_FRAMES_PER_TICK = 1000

/** Text sent when DTR falls, for every format except `justfloat`. */
export const DEMO_RESET_TEXT = '[demo] reset\r\n'

const FRAME_HEADER_1 = 0xa5
const FRAME_HEADER_2 = 0x5a
const CMD_REPORT = 0x01
const CMD_SET_INTERVAL = 0x10
const CMD_ACK = 0x90
const CRC_LENGTH = 2
const FIXED_OVERHEAD = 5
const LF = 0x0a
const CR = 0x0d
const TWO_PI = Math.PI * 2
const BASE_CHANNELS = 8

function crc16Modbus(data: Uint8Array): number {
  let crc = 0xffff
  for (const byte of data) {
    crc ^= byte
    for (let bit = 0; bit < 8; bit += 1) {
      crc = crc & 0x0001 ? (crc >>> 1) ^ 0xa001 : crc >>> 1
    }
  }
  return crc & 0xffff
}

function u16le(value: number): [number, number] {
  return [value & 0xff, (value >> 8) & 0xff]
}

function buildA5Frame(cmd: number, data: number[]): Uint8Array {
  const body: number[] = [FRAME_HEADER_1, FRAME_HEADER_2, data.length + 1, cmd, ...data]
  for (const byte of u16le(crc16Modbus(Uint8Array.from(body)))) body.push(byte)
  return Uint8Array.from(body)
}

function concatChunks(chunks: Uint8Array[]): Uint8Array {
  if (chunks.length === 1) return chunks[0] as Uint8Array
  const total = chunks.reduce((sum, chunk) => sum + chunk.length, 0)
  const bytes = new Uint8Array(total)
  let offset = 0
  for (const chunk of chunks) {
    bytes.set(chunk, offset)
    offset += chunk.length
  }
  return bytes
}

function asciiText(bytes: Uint8Array): string {
  let text = ''
  for (const byte of bytes) text += String.fromCharCode(byte)
  return text
}

function isPrintableOrEol(byte: number): boolean {
  return byte === CR || byte === LF || (byte >= 0x20 && byte <= 0x7e)
}

/** True for one of the four demo formats. */
export function isDemoFormat(value: unknown): value is DemoFormat {
  return typeof value === 'string' && (DEMO_FORMATS as readonly string[]).includes(value)
}

/** Normalizes an unknown format value to a supported one. */
export function normalizeDemoFormat(value: unknown): DemoFormat {
  return isDemoFormat(value) ? value : DEMO_FORMAT_DEFAULT
}

/** Lowest accepted interval of one format. */
export function demoIntervalMin(format: DemoFormat): number {
  return format === 'sensor-a5' ? DEMO_SENSOR_INTERVAL_MIN : DEMO_INTERVAL_MIN
}

/** True when `value` is a valid report interval of `format`. */
export function isValidDemoInterval(value: number, format: DemoFormat): boolean {
  return Number.isInteger(value) && value >= demoIntervalMin(format) && value <= DEMO_INTERVAL_MAX
}

/** Clamps/sanitizes an interval for one format; invalid values use the default. */
export function normalizeDemoInterval(
  value: unknown,
  format: DemoFormat = DEMO_FORMAT_DEFAULT,
): number {
  const min = demoIntervalMin(format)
  const fallback = format === 'sensor-a5' ? DEMO_INTERVAL_DEFAULT : DEMO_INTERVAL_DEFAULT_OTHER
  if (typeof value !== 'number' || !Number.isFinite(value)) return fallback
  return Math.min(DEMO_INTERVAL_MAX, Math.max(min, Math.round(value)))
}

/** Clamps/sanitizes the channel count. */
export function normalizeDemoChannels(value: unknown): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) return DEMO_CHANNELS_DEFAULT
  return Math.min(DEMO_CHANNELS_MAX, Math.max(DEMO_CHANNELS_MIN, Math.round(value)))
}

/** Formatting helpers shared with tests: the A5 report floats over time. */
export function demoTemperature(phase: number): number {
  return 25 + 5 * Math.sin(phase)
}

export function demoHumidity(phase: number): number {
  return 50 + 10 * Math.sin(phase * 0.7 + 1)
}

export function demoVoltage(phase: number): number {
  return 3300 + 50 * Math.sin(phase * 1.3 + 2)
}

/**
 * Value of one dashboard variable (plan §8.7).
 *
 * `base` is the channel index modulo 8; channels ≥ 8 reuse the base formula with
 * a phase offset of `k × π / 8`.
 */
export function demoVariableValue(
  base: number,
  tau: number,
  sampleIndex: number,
  amp: number,
  phaseOffset: number,
  random: () => number,
): number {
  switch (base) {
    case 1:
      return amp * Math.cos(TWO_PI * tau + phaseOffset)
    case 2:
      return amp * Math.sign(Math.sin(Math.PI * tau + phaseOffset))
    case 3: {
      const cycles = 0.2 * tau + phaseOffset / TWO_PI
      return amp * (cycles - Math.floor(cycles))
    }
    case 4:
      return 0.5 + 0.1 * (random() * 2 - 1)
    case 5:
      return (
        amp *
        (0.5 * Math.sin(TWO_PI * 50 * tau + phaseOffset) +
          0.2 * Math.sin(TWO_PI * 120 * tau + phaseOffset))
      )
    case 6:
      return 25 + 5 * Math.sin(TWO_PI * 0.05 * tau + phaseOffset)
    case 7:
      return sampleIndex
    case 0:
    default:
      return amp * Math.sin(TWO_PI * tau + phaseOffset)
  }
}

export interface DemoDeviceOptions {
  format?: string
  intervalMs?: number
  channels?: number
  /** Injectable noise source; defaults to `Math.random`. */
  random?: () => number
}

/** Behavior of one demo device. */
export class DemoDevice {
  private formatValue: DemoFormat
  private intervalMsValue: number
  private channelsValue: number
  private ampValue = DEMO_AMP_DEFAULT
  private sampleIndexValue = 0
  private sampleStart = 0
  private timer: ReturnType<typeof setInterval> | null = null
  private emit: ((bytes: Uint8Array) => void) | null = null
  private incoming: number[] = []
  private dtr: boolean | null = null
  private rts: boolean | null = null
  private readonly random: () => number

  constructor(options: DemoDeviceOptions = {}) {
    this.formatValue = normalizeDemoFormat(options.format)
    this.intervalMsValue = normalizeDemoInterval(options.intervalMs, this.formatValue)
    this.channelsValue = normalizeDemoChannels(options.channels)
    this.random = options.random ?? Math.random
  }

  get format(): DemoFormat {
    return this.formatValue
  }

  get intervalMs(): number {
    return this.intervalMsValue
  }

  get channels(): number {
    return this.channelsValue
  }

  get amp(): number {
    return this.ampValue
  }

  /** Index of the next sample (0 based). */
  get sampleIndex(): number {
    return this.sampleIndexValue
  }

  /** Number of reports sent since the last reset (compatibility helper). */
  get reportCount(): number {
    return this.sampleIndexValue
  }

  /** Starts the 10ms driver; the first sample is sent once one interval elapsed. */
  start(emit: (bytes: Uint8Array) => void): void {
    this.stop()
    this.emit = emit
    this.sampleIndexValue = 0
    this.sampleStart = this.nowMs()
    this.timer = setInterval(() => {
      this.tick()
    }, DEMO_TICK_MS)
  }

  stop(): void {
    if (this.timer !== null) {
      clearInterval(this.timer)
      this.timer = null
    }
    this.emit = null
  }

  /** Handles host → device bytes (may be a partial frame or command line). */
  receive(bytes: Uint8Array): void {
    for (const byte of bytes) this.incoming.push(byte)
    this.processIncoming()
  }

  setDtr(value: boolean): void {
    if (this.dtr === true && value === false) {
      this.sampleIndexValue = 0
      this.sampleStart = this.nowMs()
      if (this.formatValue !== 'justfloat') {
        this.emitBytes(new TextEncoder().encode(DEMO_RESET_TEXT))
      }
    }
    this.dtr = value
  }

  setRts(value: boolean): void {
    this.rts = value
  }

  /** Current requested RTS value (kept for completeness; the demo ignores it). */
  get rtsValue(): boolean | null {
    return this.rts
  }

  private nowMs(): number {
    return Date.now()
  }

  private tick(): void {
    const elapsed = this.nowMs() - this.sampleStart
    const expected = Math.floor(elapsed / this.intervalMsValue)
    const due = expected - this.sampleIndexValue
    if (due <= 0) return
    const count = Math.min(due, DEMO_MAX_FRAMES_PER_TICK)
    const chunks: Uint8Array[] = []
    for (let index = 0; index < count; index += 1) {
      chunks.push(this.buildSample(this.sampleIndexValue))
      this.sampleIndexValue += 1
    }
    this.emitBytes(concatChunks(chunks))
  }

  private buildSample(index: number): Uint8Array {
    if (this.formatValue === 'sensor-a5') return this.buildSensorFrame(index)
    const tau = (index * this.intervalMsValue) / 1000
    const channels = this.formatValue === 'kv-text' ? DEMO_TEXT_CHANNELS : this.channelsValue
    const values: number[] = []
    for (let channel = 0; channel < channels; channel += 1) {
      const phaseOffset = channel >= BASE_CHANNELS ? (channel * Math.PI) / BASE_CHANNELS : 0
      values.push(
        demoVariableValue(
          channel % BASE_CHANNELS,
          tau,
          index,
          this.ampValue,
          phaseOffset,
          this.random,
        ),
      )
    }
    switch (this.formatValue) {
      case 'firewater':
        return this.buildFireWater(values)
      case 'justfloat':
        return this.buildJustFloat(values)
      case 'kv-text':
      default:
        return this.buildKvText(values)
    }
  }

  private buildSensorFrame(index: number): Uint8Array {
    const phase = index * 0.2
    const temperature = Math.round(demoTemperature(phase) * 100)
    const humidity = Math.round(demoHumidity(phase) * 100)
    const voltage = Math.round(demoVoltage(phase))
    const data: number[] = [
      ...u16le(temperature & 0xffff),
      ...u16le(humidity & 0xffff),
      ...u16le(voltage & 0xffff),
      index & 0xff,
      (index >> 8) & 0xff,
      (index >> 16) & 0xff,
      (index >>> 24) & 0xff,
    ]
    return buildA5Frame(CMD_REPORT, data)
  }

  private buildFireWater(values: number[]): Uint8Array {
    const fields = values.map((value, index) =>
      index === BASE_CHANNELS - 1 ? String(Math.round(value)) : value.toFixed(6),
    )
    return new TextEncoder().encode(`${fields.join(',')}\n`)
  }

  private buildJustFloat(values: number[]): Uint8Array {
    const payload = new Uint8Array(values.length * 4 + 4)
    const view = new DataView(payload.buffer)
    for (let index = 0; index < values.length; index += 1) {
      view.setFloat32(index * 4, values[index] as number, true)
    }
    payload.set([0x00, 0x00, 0x80, 0x7f], values.length * 4)
    return payload
  }

  private buildKvText(values: number[]): Uint8Array {
    const fields = values.map((value, index) => `ch${index}:${value.toFixed(6)}`)
    return new TextEncoder().encode(`${fields.join(',')}\n`)
  }

  private processIncoming(): void {
    for (;;) {
      if (this.incoming.length === 0) return
      if (this.incoming[0] === FRAME_HEADER_1) {
        if (this.incoming.length < 2) return
        if (this.incoming[1] !== FRAME_HEADER_2) {
          this.incoming.shift()
          continue
        }
        if (this.incoming.length < 3) return
        const length = this.incoming[2] as number
        if (length < 1) {
          this.incoming.shift()
          continue
        }
        const total = length + FIXED_OVERHEAD
        if (this.incoming.length < total) return
        const frame = Uint8Array.from(this.incoming.slice(0, total))
        const expected = crc16Modbus(frame.subarray(0, total - CRC_LENGTH))
        const actual =
          (frame[total - CRC_LENGTH] as number) | ((frame[total - CRC_LENGTH + 1] as number) << 8)
        if (expected !== actual) {
          // Bad CRC: drop the header byte and resynchronize.
          this.incoming.shift()
          continue
        }
        this.incoming.splice(0, total)
        this.handleA5Frame(frame)
        continue
      }

      const lineFeed = this.incoming.indexOf(LF)
      if (lineFeed < 0) {
        // Incomplete text line: keep printable bytes, discard binary garbage.
        if (!this.incoming.every(isPrintableOrEol)) {
          this.incoming.length = 0
          return
        }
        // Printable data without a line terminator is not a command, so echo it
        // verbatim (plan §8.7); justfloat never echoes.
        if (this.incoming.length > 0 && this.formatValue !== 'justfloat') {
          const raw = Uint8Array.from(this.incoming)
          this.incoming.length = 0
          this.emitBytes(raw)
        }
        return
      }
      const raw = Uint8Array.from(this.incoming.slice(0, lineFeed + 1))
      this.incoming.splice(0, lineFeed + 1)
      this.handleTextLine(raw)
    }
  }

  /**
   * Commands are lines without the trailing CR/LF; anything else printable is
   * echoed verbatim (`justfloat` never echoes, plan §8.7).
   */
  private handleTextLine(raw: Uint8Array): void {
    let end = raw.length - 1
    if (end > 0 && raw[end - 1] === CR) end -= 1
    const content = asciiText(raw.subarray(0, end))
    if (content.startsWith('interval=') || content.startsWith('amp=')) {
      const ok = this.applyTextCommand(content)
      this.replyCommand(content, ok)
      return
    }
    if (this.formatValue === 'justfloat') return
    if (!raw.every(isPrintableOrEol)) return
    this.emitBytes(raw)
  }

  private applyTextCommand(content: string): boolean {
    if (content.startsWith('interval=')) {
      const value = Number(content.slice('interval='.length))
      if (!Number.isFinite(value)) return false
      if (!isValidDemoInterval(value, this.formatValue)) return false
      this.setIntervalMs(value)
      return true
    }
    if (content.startsWith('amp=')) {
      const value = Number(content.slice('amp='.length))
      if (!Number.isFinite(value)) return false
      if (value < DEMO_AMP_MIN || value > DEMO_AMP_MAX) return false
      this.ampValue = value
      return true
    }
    return false
  }

  private replyCommand(content: string, ok: boolean): void {
    if (this.formatValue !== 'firewater' && this.formatValue !== 'kv-text') return
    const text = ok ? `OK ${content}\n` : `ERR ${content}\n`
    this.emitBytes(new TextEncoder().encode(text))
  }

  private setIntervalMs(value: number): void {
    this.intervalMsValue = value
    // Keep the already sent samples: sample `n` is due one new interval later.
    this.sampleStart = this.nowMs() - this.sampleIndexValue * value
  }

  private handleA5Frame(frame: Uint8Array): void {
    if (this.formatValue !== 'sensor-a5') return
    if ((frame[3] as number) !== CMD_SET_INTERVAL) return
    if ((frame[2] as number) !== 3) return
    const requested = (frame[4] as number) | ((frame[5] as number) << 8)
    const valid = isValidDemoInterval(requested, this.formatValue)
    if (valid) this.setIntervalMs(requested)
    const status = valid ? 0 : 1
    this.emitBytes(buildA5Frame(CMD_ACK, [status, ...u16le(this.intervalMsValue)]))
  }

  private emitBytes(bytes: Uint8Array): void {
    this.emit?.(bytes)
  }
}

/** In-memory `ByteTransport` that drives a `DemoDevice`. */
export class VirtualTransport implements ByteTransport {
  readonly kind = 'virtual'
  readonly deviceKey = VIRTUAL_DEVICE_KEY
  readonly capabilities: TransportCapabilities = VIRTUAL_CAPABILITIES

  private readableStream: ReadableStream<Uint8Array> | null = null
  private writableStream: WritableStream<Uint8Array> | null = null
  private controller: ReadableStreamDefaultController<Uint8Array> | null = null
  private device: DemoDevice | null = null
  private lastFormat: DemoFormat = DEMO_FORMAT_DEFAULT
  private lastInterval: number = DEMO_INTERVAL_DEFAULT
  private lastChannels: number = DEMO_CHANNELS_DEFAULT

  constructor(readonly label: string) {}

  get readable(): ReadableStream<Uint8Array> | null {
    return this.readableStream
  }

  get writable(): WritableStream<Uint8Array> | null {
    return this.writableStream
  }

  get format(): DemoFormat {
    return this.device?.format ?? this.lastFormat
  }

  get intervalMs(): number {
    return this.device?.intervalMs ?? this.lastInterval
  }

  get channels(): number {
    return this.device?.channels ?? this.lastChannels
  }

  async open(settings: Record<string, unknown>): Promise<void> {
    const format = normalizeDemoFormat(settings.format)
    const interval = normalizeDemoInterval(settings.interval, format)
    const channels = normalizeDemoChannels(settings.channels)
    this.lastFormat = format
    this.lastInterval = interval
    this.lastChannels = channels
    this.device = new DemoDevice({ format, intervalMs: interval, channels })
    this.readableStream = new ReadableStream<Uint8Array>({
      start: (controller) => {
        this.controller = controller
      },
      cancel: () => {
        this.controller = null
      },
    })
    this.writableStream = new WritableStream<Uint8Array>({
      write: (chunk) => {
        this.device?.receive(Uint8Array.from(chunk))
      },
    })
    this.device.start((bytes) => {
      this.enqueue(bytes)
    })
  }

  async close(): Promise<void> {
    this.device?.stop()
    this.device = null
    const controller = this.controller
    this.controller = null
    if (controller !== null) {
      try {
        controller.close()
      } catch {
        // The reader may have been cancelled already.
      }
    }
    this.readableStream = null
    this.writableStream = null
  }

  async setSignals(signals: TransportSignals): Promise<void> {
    if (signals.dtr !== undefined) this.device?.setDtr(signals.dtr)
    if (signals.rts !== undefined) this.device?.setRts(signals.rts)
    // `capabilities.break` is false: break is intentionally ignored.
  }

  onDisconnect(): () => void {
    // A virtual transport never disconnects.
    return () => {}
  }

  isSameDevice(other: ByteTransport): boolean {
    return other === this
  }

  private enqueue(bytes: Uint8Array): void {
    const controller = this.controller
    if (controller === null) return
    try {
      controller.enqueue(bytes)
    } catch {
      // The stream may have been closed between the timer and this call.
    }
  }
}
